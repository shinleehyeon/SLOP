export const FIELD_TERM_SYSTEM_PROMPT =
  '당신은 숏폼 영상 서비스 Shortlens의 온보딩 콘텐츠 생성기입니다. 주어진 관심 분야에서 대표적인 전문 용어 2개를 선정하고, 각 용어를 쉬움/보통/어려움 세 난이도로 표현한 예시 문장을 만드세요.';

export function buildFieldTermUserPrompt(fieldName: string, tone: string): string {
  return `
분야: ${fieldName}
어투: ${tone} (CASUAL=반말, POLITE=존댓말, NEWS=뉴스체 — 문장 종결어미에 반영)

규칙:
1. 이모지, 아이콘, 특수기호는 절대 사용하지 마세요.
2. 각 난이도 문장은 반드시 하나의 완결된 문장으로 작성하세요 (마침표 하나, 두 문장을 잇지 말 것).
3. 한 문장 안에 사용자가 난이도를 스스로 판단할 수 있는 기준을 2~3개 포함하세요. 예: 구체적 수치/데이터 포함 여부, 전문 용어를 그대로 쓰는지 풀어 쓰는지, 인과관계나 비교를 얼마나 압축적으로 서술하는지.
4. 쉬움은 초등학생도 이해할 일상어, 보통은 일반 성인 눈높이, 어려움은 해당 분야 전공자 수준의 용어·논리 구조로 작성하세요.
5. 세 난이도 문장은 동일한 사실을 전달해야 하며 정보 왜곡이 없어야 합니다.
6. 실제 최근 이슈가 될 법한 소재를 활용해 자연스럽게 작성하세요.

출력은 반드시 아래 JSON 형식만 반환하세요. 다른 설명 텍스트는 포함하지 마세요.
{
  "field": "${fieldName}",
  "terms": [
    { "term": "...", "easy": "...", "medium": "...", "hard": "..." },
    { "term": "...", "easy": "...", "medium": "...", "hard": "..." }
  ]
}
`.trim();
}
